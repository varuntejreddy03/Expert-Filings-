export function getServiceBySlug(slug) {
  return services.find((service) => service.slug === slug);
}

export function getRelatedServices(service) {
  if (!service) return [];

  const preferred = (service.related || [])
    .map((slug) => getServiceBySlug(slug))
    .filter(Boolean);

  const fallback = services
    .filter((item) => item.category === service.category && item.slug !== service.slug)
    .slice(0, 3);

  return [...preferred, ...fallback]
    .filter((item, index, array) => item && array.findIndex((match) => match.slug === item.slug) === index)
    .slice(0, 3);
}
